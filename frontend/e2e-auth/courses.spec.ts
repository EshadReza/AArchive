import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('admin creates, edits, filters and archives a reusable department course', async ({ page }, info) => {
  const suffix = info.project.name.toUpperCase();
  const department = `CAT-${suffix}`; const code = `CS101-${suffix}`;
  await page.goto('/login');
  await page.getByLabel('Institutional email').fill(`lifecycle-admin-${info.project.name}@iut.example`);
  await page.getByLabel('Password', { exact: false }).fill('synthetic-browser-password-123');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Manage academic structure' }).click();
  await page.getByLabel('Label', { exact: false }).fill(department);
  await page.getByLabel('Name', { exact: false }).fill('Catalog department');
  await page.getByRole('button', { name: 'Save record' }).click();
  await expect(page.getByRole('button', { name: `Edit ${department}`, exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Back to account' }).click();
  await page.getByRole('link', { name: 'Manage course catalog' }).click();
  await page.getByRole('radio', { name: `${department} — Catalog department` }).check();
  await page.getByLabel('Course code', { exact: false }).fill(code);
  await page.getByLabel('Course title', { exact: false }).fill('Programming foundations');
  await page.getByLabel('Credits', { exact: false }).fill('3.50');
  await page.getByLabel('Description', { exact: true }).fill('Learn programming.\nReusable across terms.');
  await page.getByRole('button', { name: 'Save course' }).click();
  await expect(page.getByRole('heading', { name: `${code} — Programming foundations` })).toBeVisible();
  await page.getByRole('button', { name: `Edit ${code}`, exact: true }).click();
  await expect(page.getByText(/fixed after creation/)).toBeVisible();
  await page.getByLabel('Course title', { exact: false }).fill('Programming fundamentals');
  await page.getByRole('button', { name: 'Save course' }).click();
  await expect(page.getByRole('heading', { name: `${code} — Programming fundamentals` })).toBeVisible();
  await page.getByLabel('Search courses').fill(code);
  await page.getByRole('checkbox', { name: 'Limit to selected department' }).check();
  await page.getByRole('button', { name: 'Apply filters' }).click();
  await expect(page.getByRole('heading', { name: `${code} — Programming fundamentals` })).toBeVisible();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: `test-results/courses-${info.project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: `Archive ${code}`, exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review course archive' })).toBeFocused();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: `Archive ${code}`, exact: true }).click();
  await page.getByRole('button', { name: 'Confirm archive' }).click();
  await expect(page.getByRole('button', { name: `Edit ${code}`, exact: true })).toBeDisabled();
  await expect(page.getByText('3.50 credits · Archived', { exact: true })).toBeVisible();
  await expect(page.getByText('Learn programming.\nReusable across terms.', { exact: true })).toBeVisible();
});
